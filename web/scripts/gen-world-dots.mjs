// Regenerates src/lib/world-dots.ts, the dotted map behind the sign-in page.
// dotted-map is not a project dependency; install it only to run this:
//   npm i --no-save dotted-map@3.1.0 && node scripts/gen-world-dots.mjs
import { writeFileSync } from "node:fs";
import DottedMap from "dotted-map";

// The Middle East to the western Pacific, the stretch the panel's relays span.
const region = { lat: { min: -14, max: 58 }, lng: { min: 36, max: 180 } };
const cities = {
  DXB: { lat: 25.2, lng: 55.27 },
  BOM: { lat: 19.08, lng: 72.88 },
  SHA: { lat: 31.23, lng: 121.47 },
  HKG: { lat: 22.32, lng: 114.17 },
  TPE: { lat: 25.03, lng: 121.56 },
  TYO: { lat: 35.68, lng: 139.69 },
  SIN: { lat: 1.35, lng: 103.82 },
};

const map = new DottedMap({ height: 64, grid: "diagonal", region });
for (const [code, { lat, lng }] of Object.entries(cities)) map.addPin({ lat, lng, data: code });

const points = map.getPoints();
const land = points.filter((p) => !p.data);
const pins = Object.fromEntries(points.filter((p) => p.data).map((p) => [p.data, [round(p.x), round(p.y)]]));
const width = Math.ceil(Math.max(...points.map((p) => p.x)) + 1);
const height = Math.ceil(Math.max(...points.map((p) => p.y)) + 1);

function round(value) {
  return Math.round(value * 10) / 10;
}

const source = `// Generated by scripts/gen-world-dots.mjs with dotted-map 3.1.0 (MIT,
// Natural Earth data). Do not edit by hand.

export const MAP_WIDTH = ${width};
export const MAP_HEIGHT = ${height};

/** Land dots as flat x,y pairs in map units. */
export const LAND_DOTS: readonly number[] = [${land.map((p) => `${round(p.x)},${round(p.y)}`).join(",")}];

export const CITY_DOTS = ${JSON.stringify(pins)} as const satisfies Record<string, readonly [number, number]>;
`;
writeFileSync(new URL("../src/lib/world-dots.ts", import.meta.url), source);
console.log(`${land.length} land dots, ${Object.keys(pins).length} cities, ${width}x${height}`);
